sobrenome = input("Informe o seu sobrenome: ")

if(sobrenome == "calvo" or sobrenome == "Calvo"):
    print("Você pertence à família Calvo")
elif(sobrenome == "silva" or sobrenome == "Silva"):
    print("Você pertence à família Silva")
else:
    print("Sinto muito. Você não pertence nem à família Calvo nem à família Silva.")